-- Per-app opacity: { active, inactive }
local opacityRules = {
    kitty    = "0.79 0.77",
    vesktop  = "1 0.96",
    discord  = "1 0.96",
    firefox  = "1 1",
    rofi     = "0.75 0.75",
    obsidian = "1 0.98",
}

for class, opacity in pairs(opacityRules) do
    hl.window_rule({
        name    = "opacity-" .. class,
        match   = { class = class },
        opacity = opacity,
    })
end

hl.window_rule({
    -- Ignore maximize requests from all apps. You'll probably like this.
    name  = "suppress-maximize-events",
    match = { class = ".*" },

    suppress_event = "maximize",
})

hl.window_rule({
    -- Fix some dragging issues with XWayland
    name  = "fix-xwayland-drags",
    match = {
        class      = "^$",
        title      = "^$",
        xwayland   = true,
        float      = true,
        fullscreen = false,
        pin        = false,
    },

    no_focus = true,
})

-- Hyprland-run windowrule
hl.window_rule({
    name  = "move-hyprland-run",
    match = { class = "hyprland-run" },

    move  = "20 monitor_h-120",
    float = true,
})

